class FundJJJZDataResponse(object):
    def __init__(self, chars=[], datas=[], count=[], record='0', pages='1', curpage='1', indexsy=[], showday=[]):
        self.chars = chars
        self.datas = datas
        self.count = count
        self.record = record
        self.pages = pages
        self.curpage = curpage
        self.indexsy = indexsy
        self.showday = showday

def dict_to_fund_jjjz_data_response(d:dict):
    return FundJJJZDataResponse(d['chars'],
                                d['datas'],
                                d['count'],
                                d['record'],
                                d['pages'],
                                d['curpage'],
                                d['indexsy'],
                                d['showday'])
