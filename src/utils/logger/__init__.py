''' 定义logging的interface

'''
#-----------------------------------------------------------------------------
# Boilerplate
#-----------------------------------------------------------------------------
from __future__ import annotations

#-----------------------------------------------------------------------------
# Imports
#-----------------------------------------------------------------------------
import logging

#-----------------------------------------------------------------------------
# Globals and constants
#-----------------------------------------------------------------------------
__all__ = ['getLogger']

#-----------------------------------------------------------------------------
# General API
#-----------------------------------------------------------------------------
def getLogger(name=None):
    return logging.getLogger(name)

#-----------------------------------------------------------------------------
# Dev API
#-----------------------------------------------------------------------------

#-----------------------------------------------------------------------------
# Private API
#-----------------------------------------------------------------------------

#-----------------------------------------------------------------------------
# Code
#-----------------------------------------------------------------------------
# 配置 logging
logging.basicConfig(
    level=logging.DEBUG,  # 设置日志级别
    format="%(asctime)s - %(levelname)s - %(message)s",  # 定义日志格式
    datefmt="%Y-%m-%d %H:%M:%S"
)