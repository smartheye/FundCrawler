#-----------------------------------------------------------------------------
# Imports
#-----------------------------------------------------------------------------
from abc import ABC, abstractmethod

#-----------------------------------------------------------------------------
# Globals and constants
#-----------------------------------------------------------------------------

#-----------------------------------------------------------------------------
# General API
#-----------------------------------------------------------------------------
class BaseTask:
    """所有任务的基类
    """

    def __init__(self, name):
        self.name = name

    @abstractmethod
    def run(self):
        pass

    @abstractmethod
    def cleanup(self):
        pass

class GeneralTask(BaseTask):
    """空白任务
    """

    def __init__(self, name):
        super().__init__(name)

    def run(self):
        pass

    def cleanup(self):
        pass

